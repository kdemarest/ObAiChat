const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const SOURCE = path.join(ROOT, "src/ui/chat-view.js");
const OUT_DIR = path.join(ROOT, "src/ui/split-rough");

const PARTS = {
  runtime: "01-runtime-and-svelte.js",
  chatContainer: "02-chat-container.js",
  chatView: "03-chat-view.js"
};

const CHAT_CONTAINER_MARKER = "// src/ui/ChatContainer.svelte";
const VIEW_MARKER = "// src/ui/chat-view.ts";

function readSource() {
  if (!fs.existsSync(SOURCE)) {
    throw new Error(`Source file not found: ${SOURCE}`);
  }
  return fs.readFileSync(SOURCE, "utf8");
}

function ensureOutDir() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
}

function splitSource(source) {
  const chatContainerStart = source.indexOf(CHAT_CONTAINER_MARKER);
  if (chatContainerStart < 0) {
    throw new Error(`Could not find marker: ${CHAT_CONTAINER_MARKER}`);
  }

  const firstViewMarker = source.indexOf(VIEW_MARKER);
  const viewStart = source.lastIndexOf(VIEW_MARKER);
  if (viewStart < 0 || firstViewMarker === viewStart) {
    throw new Error(
      "Could not find the second // src/ui/chat-view.ts marker needed for splitting."
    );
  }

  const runtime = source.slice(0, chatContainerStart).trimStart();
  const chatContainer = source.slice(chatContainerStart, viewStart).trimStart();
  const chatView = source.slice(viewStart).trimStart();

  return { runtime, chatContainer, chatView };
}

function writeParts(parts) {
  ensureOutDir();

  fs.writeFileSync(path.join(OUT_DIR, PARTS.runtime), parts.runtime + "\n");
  fs.writeFileSync(path.join(OUT_DIR, PARTS.chatContainer), parts.chatContainer + "\n");
  fs.writeFileSync(path.join(OUT_DIR, PARTS.chatView), parts.chatView + "\n");

  const readme = [
    "## Rough split output",
    "",
    "Generated by gptchat/chatViewSplitRough.script.sh.",
    "",
    "Files:",
    "- 01-runtime-and-svelte.js",
    "- 02-chat-container.js",
    "- 03-chat-view.js",
    "",
    "Notes:",
    "- This is a rough textual split for easier editing.",
    "- These files are not independent runtime modules.",
    "- Use merge mode to rebuild src/ui/chat-view.js.",
    ""
  ].join("\n");

  fs.writeFileSync(path.join(OUT_DIR, "README.md"), readme);
}

function mergeParts() {
  const runtimePath = path.join(OUT_DIR, PARTS.runtime);
  const chatContainerPath = path.join(OUT_DIR, PARTS.chatContainer);
  const chatViewPath = path.join(OUT_DIR, PARTS.chatView);

  for (const p of [runtimePath, chatContainerPath, chatViewPath]) {
    if (!fs.existsSync(p)) {
      throw new Error(`Missing split part: ${p}`);
    }
  }

  const merged = [
    fs.readFileSync(runtimePath, "utf8").trimEnd(),
    "",
    fs.readFileSync(chatContainerPath, "utf8").trimEnd(),
    "",
    fs.readFileSync(chatViewPath, "utf8").trimEnd(),
    ""
  ].join("\n");

  fs.writeFileSync(SOURCE, merged);
}

function printUsage() {
  console.log("Usage:");
  console.log("  node gptchat/chatViewSplitRough.script.sh split");
  console.log("  node gptchat/chatViewSplitRough.script.sh merge");
}

function main() {
  const mode = (process.argv[2] || "split").toLowerCase();

  if (mode === "split") {
    const source = readSource();
    const parts = splitSource(source);
    writeParts(parts);
    console.log("Rough split complete:");
    console.log(`- ${path.join(OUT_DIR, PARTS.runtime)}`);
    console.log(`- ${path.join(OUT_DIR, PARTS.chatContainer)}`);
    console.log(`- ${path.join(OUT_DIR, PARTS.chatView)}`);
    return;
  }

  if (mode === "merge") {
    mergeParts();
    console.log(`Merged split parts back into: ${SOURCE}`);
    return;
  }

  printUsage();
  process.exitCode = 1;
}

main();
