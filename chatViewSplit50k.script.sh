const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const SOURCE = path.join(ROOT, "src/ui/chat-view.js");
const OUT_DIR = path.join(ROOT, "src/ui/split-50k");
const MANIFEST = path.join(OUT_DIR, "manifest.json");

const CHAT_CONTAINER_MARKER = "// src/ui/ChatContainer.svelte";
const VIEW_MARKER = "// src/ui/chat-view.ts";

function parseArgs(argv) {
  const mode = (argv[2] || "split").toLowerCase();
  let maxBytes = 50 * 1024;

  for (let i = 3; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--max-bytes") {
      const next = Number.parseInt(argv[i + 1], 10);
      if (Number.isFinite(next) && next > 0) {
        maxBytes = next;
        i++;
      }
    } else if (arg.startsWith("--max-bytes=")) {
      const next = Number.parseInt(arg.slice("--max-bytes=".length), 10);
      if (Number.isFinite(next) && next > 0) {
        maxBytes = next;
      }
    }
  }

  return { mode, maxBytes };
}

function ensureOutDir() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
}

function readSource() {
  if (!fs.existsSync(SOURCE)) {
    throw new Error(`Source file not found: ${SOURCE}`);
  }
  return fs.readFileSync(SOURCE, "utf8");
}

function splitTopLevel(source) {
  const chatContainerStart = source.indexOf(CHAT_CONTAINER_MARKER);
  if (chatContainerStart < 0) {
    throw new Error(`Could not find marker: ${CHAT_CONTAINER_MARKER}`);
  }

  const viewStart = source.lastIndexOf(VIEW_MARKER);
  const firstViewStart = source.indexOf(VIEW_MARKER);
  if (viewStart < 0 || firstViewStart === viewStart) {
    throw new Error("Could not find second // src/ui/chat-view.ts marker.");
  }

  return [
    {
      key: "runtime",
      filePrefix: "01-runtime",
      text: source.slice(0, chatContainerStart).trimStart()
    },
    {
      key: "chat-container",
      filePrefix: "02-chat-container",
      text: source.slice(chatContainerStart, viewStart).trimStart()
    },
    {
      key: "chat-view",
      filePrefix: "03-chat-view",
      text: source.slice(viewStart).trimStart()
    }
  ];
}

function byteLen(s) {
  return Buffer.byteLength(s, "utf8");
}

function chunkByMaxBytes(text, maxBytes) {
  if (byteLen(text) <= maxBytes) return [text];

  const lines = text.split("\n");
  const chunks = [];
  let current = [];
  let currentBytes = 0;

  for (const line of lines) {
    const lineWithNl = line + "\n";
    const lineBytes = byteLen(lineWithNl);

    if (lineBytes > maxBytes) {
      if (current.length > 0) {
        chunks.push(current.join("\n").replace(/\n$/, ""));
        current = [];
        currentBytes = 0;
      }

      const raw = line;
      let offset = 0;
      while (offset < raw.length) {
        let take = Math.min(raw.length - offset, Math.max(1, Math.floor(maxBytes * 0.9)));
        let piece = raw.slice(offset, offset + take);

        while (piece && byteLen(piece + "\n") > maxBytes) {
          take = Math.max(1, Math.floor(take * 0.8));
          piece = raw.slice(offset, offset + take);
          if (take === 1) break;
        }

        chunks.push(piece);
        offset += piece.length;
      }
      continue;
    }

    if (currentBytes + lineBytes > maxBytes && current.length > 0) {
      chunks.push(current.join("\n"));
      current = [line];
      currentBytes = byteLen(line + "\n");
    } else {
      current.push(line);
      currentBytes += lineBytes;
    }
  }

  if (current.length > 0) {
    chunks.push(current.join("\n"));
  }

  return chunks.filter((c) => c.length > 0);
}

function writeSplit(maxBytes) {
  const source = readSource();
  const sections = splitTopLevel(source);
  ensureOutDir();

  const manifest = {
    generatedAt: new Date().toISOString(),
    source: path.relative(ROOT, SOURCE),
    maxBytes,
    parts: []
  };

  for (const section of sections) {
    const chunks = chunkByMaxBytes(section.text, maxBytes);
    chunks.forEach((chunk, idx) => {
      const filename = `${section.filePrefix}.part${String(idx + 1).padStart(2, "0")}.js`;
      const fullPath = path.join(OUT_DIR, filename);
      const finalText = chunk.endsWith("\n") ? chunk : chunk + "\n";
      fs.writeFileSync(fullPath, finalText);

      manifest.parts.push({
        section: section.key,
        filename,
        bytes: byteLen(finalText)
      });
    });
  }

  fs.writeFileSync(MANIFEST, JSON.stringify(manifest, null, 2) + "\n");

  const readme = [
    "## split-50k output",
    "",
    "Generated by gptchat/chatViewSplit50k.script.sh.",
    "",
    `- Source: ${path.relative(ROOT, SOURCE)}`,
    `- Max bytes per part: ${maxBytes}`,
    "- Merge order is controlled by manifest.json",
    "",
    "Commands:",
    "- node gptchat/chatViewSplit50k.script.sh split",
    "- node gptchat/chatViewSplit50k.script.sh split --max-bytes 51200",
    "- node gptchat/chatViewSplit50k.script.sh merge",
    ""
  ].join("\n");
  fs.writeFileSync(path.join(OUT_DIR, "README.md"), readme);

  return manifest;
}

function mergeSplit() {
  if (!fs.existsSync(MANIFEST)) {
    throw new Error(`Manifest missing: ${MANIFEST}`);
  }

  const manifest = JSON.parse(fs.readFileSync(MANIFEST, "utf8"));
  if (!manifest || !Array.isArray(manifest.parts) || manifest.parts.length === 0) {
    throw new Error("Invalid manifest.json: no parts found.");
  }

  const merged = [];
  for (const part of manifest.parts) {
    const fullPath = path.join(OUT_DIR, part.filename);
    if (!fs.existsSync(fullPath)) {
      throw new Error(`Missing part file: ${fullPath}`);
    }
    merged.push(fs.readFileSync(fullPath, "utf8").trimEnd());
  }

  const output = merged.join("\n\n") + "\n";
  fs.writeFileSync(SOURCE, output);
}

function printSummary(manifest) {
  console.log(`Split complete: ${manifest.parts.length} file(s)`);
  let over = 0;
  for (const part of manifest.parts) {
    const mark = part.bytes > manifest.maxBytes ? " [OVER LIMIT]" : "";
    if (mark) over += 1;
    console.log(`- ${part.filename}: ${part.bytes} bytes${mark}`);
  }
  if (over === 0) {
    console.log("All parts are within max-bytes limit.");
  }
}

function printUsage() {
  console.log("Usage:");
  console.log("  node gptchat/chatViewSplit50k.script.sh split [--max-bytes 51200]");
  console.log("  node gptchat/chatViewSplit50k.script.sh merge");
}

function main() {
  const { mode, maxBytes } = parseArgs(process.argv);

  if (mode === "split") {
    const manifest = writeSplit(maxBytes);
    printSummary(manifest);
    return;
  }

  if (mode === "merge") {
    mergeSplit();
    console.log(`Merged into ${SOURCE}`);
    return;
  }

  printUsage();
  process.exitCode = 1;
}

main();
